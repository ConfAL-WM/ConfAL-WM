def _manifest_records(cfg: dict[str, Any]) -> tuple[list[EpisodeRecord], list[EpisodeRecord]]:
    manifest_cfg = cfg["manifest"]
    manifest_path = manifest_cfg.get("path")
    builder_cfg = manifest_cfg.get("builder", {})
    if manifest_path is None:
        standardized_root = builder_cfg.get("standardized_root")
        if standardized_root is None:
            raise ValueError("Must provide manifest.path, or manifest.builder.standardized_root to auto-build manifest")
        manifest_path = build_manifest_from_standardized_root(
            standardized_root=standardized_root,
            gt_root=manifest_cfg.get("gt_root"),
            split=builder_cfg.get("split", "val"),
            output_path=builder_cfg.get("output_path"),
        )
    all_records = load_manifest(manifest_path, gt_root=manifest_cfg.get("gt_root"))
    active_records = all_records
    if manifest_cfg.get("split"):
        wanted = {part.strip() for part in str(manifest_cfg["split"]).split(",") if part.strip()}
        active_records = [record for record in all_records if record.split in wanted]
    if not active_records:
        raise ValueError("No episodes to evaluate after filtering by split")
    return all_records, active_records


def _episode_summary_row(episode: dict) -> dict[str, Any]:
    row = {
        "episode_id": episode["episode_id"],
        "split": episode["split"],
        "ood_type": episode["ood_type"],
        "num_frames": int(episode["risk_map"].shape[0]),
        "conf_mean": float(np.mean(episode["confidence_map"])),
        "risk_mean": float(np.mean(episode["risk_map"])),
        "oracle_error_mean": float(np.mean(episode["oracle_error"])),
        "trajectory_risk": episode["trajectory_risk"],
        "trajectory_error": episode["trajectory_error"],
    }
    row.update(episode["episode_metrics"])
    if episode.get("process_metrics") is not None:
        proc = dict(episode["process_metrics"])
        proc.pop("lagged_corr_lags", None)
        proc.pop("lagged_corr_values", None)
        row.update(proc)
    return row


def _flatten_summary_dict(summary: dict[str, Any]) -> dict[str, Any]:
    flat: dict[str, Any] = {}
    for key, value in summary.items():
        if isinstance(value, (list, tuple, np.ndarray)):
            continue
        flat[key] = value
    return flat


def _episode_from_record(
    record: EpisodeRecord,
    oracle_type: str,
    frame_agg_mode: str = "mean",
    frame_topk_ratio: float = 0.1,
    frame_quantile: float = 0.95,
) -> dict[str, Any]:
    conf_map = load_conf_map(record.conf_map_path)
    confidence = np.asarray(conf_map, dtype=np.float32)

    pred_frames = None
    gt_frames = None
    if oracle_type == "pixel":
        pred_frames = load_frames(record.pred_frames_dir, record.pred_video, n_frames=confidence.shape[0])
        gt_frames = load_frames(record.gt_frames_dir, record.gt_video, n_frames=confidence.shape[0])
        oracle_error = compute_pixel_oracle_error_map(pred_frames, gt_frames, confidence.shape)
    elif oracle_type == "latent":
        if record.latent_pred_path is None or record.latent_gt_path is None:
            raise ValueError(
                f"episode={record.episode_id}: latent oracle selected but manifest does not provide latent_pred_path/latent_gt_path"
            )
        pred_latent = np.load(record.latent_pred_path)
        gt_latent = np.load(record.latent_gt_path)
        oracle_error = compute_latent_oracle_error_map(pred_latent, gt_latent, confidence.shape)
    else:
        raise ValueError(f"Unsupported oracle.type: {oracle_type}")

    # Align time dimension. Generated frames, GT frames, and oracle_error may have
    # mismatched lengths (e.g., 128 generated vs 31 GT frames). Explicitly truncate to
    # the common shortest length to avoid shape mismatch in patch/frame correlations.
    num_frames = int(min(confidence.shape[0], oracle_error.shape[0]))
    if pred_frames is not None:
        num_frames = min(num_frames, int(pred_frames.shape[0]))
    if gt_frames is not None:
        num_frames = min(num_frames, int(gt_frames.shape[0]))
    if num_frames <= 0:
        raise ValueError(f"episode={record.episode_id} has no valid aligned frames")

    confidence = confidence[:num_frames]
    oracle_error = oracle_error[:num_frames]
    risk = 1.0 - confidence
    if pred_frames is not None:
        pred_frames = pred_frames[:num_frames]
    if gt_frames is not None:
        gt_frames = gt_frames[:num_frames]

    episode = {
        "episode_id": record.episode_id,
        "split": record.split,
        "ood_type": record.ood_type,
        "confidence_map": confidence,
        "risk_map": risk,
        "oracle_error": oracle_error,
        "patch_conf": confidence.reshape(-1),
        "patch_risk": risk.reshape(-1),
        "patch_error": oracle_error.reshape(-1),
        "pred_frames": pred_frames,
        "gt_frames": gt_frames,
        "is_ood": is_ood_record(record.to_dict()),
    }
    frame_risk = aggregate_map_per_frame(
        risk, mode=frame_agg_mode, topk_ratio=frame_topk_ratio, quantile=frame_quantile
    )
    frame_error = aggregate_map_per_frame(
        oracle_error, mode=frame_agg_mode, topk_ratio=frame_topk_ratio, quantile=frame_quantile
    )
    episode["frame_risk"] = frame_risk
    episode["frame_error"] = frame_error
    episode["trajectory_risk"] = float(np.mean(frame_risk))
    episode["trajectory_error"] = float(np.mean(frame_error))
    return episode


def _qualitative_metric_value(episode: dict[str, Any], metric_name: str) -> float:
    if metric_name in episode:
        value = episode[metric_name]
    else:
        value = episode.get("episode_metrics", {}).get(metric_name, np.nan)
    value = float(value) if value is not None else float("nan")
    return value if np.isfinite(value) else float("nan")


def _select_qualitative_episodes(
    episodes: list[dict[str, Any]],
    metric_name: str,
) -> list[tuple[str, dict[str, Any], str | None]]:
    """
    Select "best" and "worst" cases for qualitative_mode=single.

    Uses patch_spearman by default because the main metric of this evaluation is
    patch-level signal validity. Higher values indicate stronger rank consistency
    between risk and oracle error, making it a good best/worst criterion.
    """
    if not episodes:
        return []

    scored: list[tuple[float, dict[str, Any]]] = []
    for episode in episodes:
        score = _qualitative_metric_value(episode, metric_name)
        scored.append((score, episode))

    finite_scored = [(score, episode) for score, episode in scored if np.isfinite(score)]
    if not finite_scored:
        return [("qualitative", episodes[0], "Auto-selected qualitative case")]

    finite_scored.sort(key=lambda item: item[0])
    worst_score, worst_episode = finite_scored[0]
    best_score, best_episode = finite_scored[-1]
    worst_score_tag = f"{worst_score:.4f}".replace(".", "p")
    best_score_tag = f"{best_score:.4f}".replace(".", "p")

    selections: list[tuple[str, dict[str, Any], str | None]] = [
        (
            f"worst_{metric_name}_{worst_score_tag}",
            worst_episode,
            f"Auto-selected worst case by {metric_name} = {worst_score:.4f}",
        ),
    ]
    if best_episode["episode_id"] != worst_episode["episode_id"]:
        selections.append(
            (
                f"best_{metric_name}_{best_score_tag}",
                best_episode,
                f"Auto-selected best case by {metric_name} = {best_score:.4f}",
            )
        )
    return selections


def _bootstrap_metrics(
    summary: dict[str, Any],
    episodes: list[dict],
    cfg: dict[str, Any],
    tau_operational: float,
) -> dict[str, Any]:
    if not cfg["bootstrap"]["enabled"]:
        return summary
    num_bootstrap = int(cfg["bootstrap"]["num_bootstrap"])
    seed = int(cfg["bootstrap"]["seed"])
    ci = float(cfg["bootstrap"]["ci"])
    high_error_qs = cfg["signal_validity"]["high_error_qs"]
    scope = cfg["signal_validity"]["high_error_scope"]

    def metric_pooled_spearman(sampled: list[dict]) -> float:
        values = compute_global_signal_summary(
            sampled,
            high_error_qs=high_error_qs,
            high_error_scope=scope,
            topk_overlap_enabled=False,
        )
        return float(values.get("pooled_patch_spearman", np.nan))

    def metric_pooled_pearson(sampled: list[dict]) -> float:
        values = compute_global_signal_summary(
            sampled,
            high_error_qs=high_error_qs,
            high_error_scope=scope,
            topk_overlap_enabled=False,
        )
        return float(values.get("pooled_patch_pearson", np.nan))

    def metric_ece(sampled: list[dict]) -> float:
        conf = np.concatenate([ep["patch_conf"] for ep in sampled], axis=0)
        err = np.concatenate([ep["patch_error"] for ep in sampled], axis=0)
        return float(
            compute_calibration_stats(
                conf,
                err,
                tau=tau_operational,
                num_bins=int(cfg["calibration"]["num_bins"]),
                correctness_mode=cfg["calibration"]["correctness_mode"],
                soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
            )["ece"]
        )

    def metric_brier(sampled: list[dict]) -> float:
        conf = np.concatenate([ep["patch_conf"] for ep in sampled], axis=0)
        err = np.concatenate([ep["patch_error"] for ep in sampled], axis=0)
        return float(
            compute_calibration_stats(
                conf,
                err,
                tau=tau_operational,
                num_bins=int(cfg["calibration"]["num_bins"]),
                correctness_mode=cfg["calibration"]["correctness_mode"],
                soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
            )["brier"]
        )

    ci_specs = {
        "pooled_patch_spearman": metric_pooled_spearman,
        "pooled_patch_pearson": metric_pooled_pearson,
        "operational_ece": metric_ece,
        "operational_brier": metric_brier,
    }

    for q in high_error_qs:
        metric_name_auroc = f"high_error_top{int(q)}_auroc"
        metric_name_auprc = f"high_error_top{int(q)}_auprc"

        def _make_metric(name: str):
            def _fn(sampled: list[dict]) -> float:
                values = compute_global_signal_summary(
                    sampled,
                    high_error_qs=high_error_qs,
                    high_error_scope=scope,
                    topk_overlap_enabled=False,
                )
                return float(values.get(name, np.nan))
            return _fn

        ci_specs[metric_name_auroc] = _make_metric(metric_name_auroc)
        ci_specs[metric_name_auprc] = _make_metric(metric_name_auprc)

    for name, fn in ci_specs.items():
        ci_value = bootstrap_episode_metric(episodes, fn, num_bootstrap=num_bootstrap, seed=seed, ci=ci)
        summary[f"{name}_ci_low"] = ci_value.low
        summary[f"{name}_ci_high"] = ci_value.high
        summary[f"{name}_ci_mean"] = ci_value.mean
        summary[f"{name}_ci_num_valid_samples"] = ci_value.num_valid_samples

    return summary


def run(cfg: dict[str, Any]) -> dict[str, Any]:
    _set_seed(int(cfg["misc"]["seed"]))

    output_dir = ensure_dir(cfg["output"]["dir"])
    _cleanup_output_artifacts(output_dir)
    plots_dir = ensure_dir(output_dir / "plots")
    qual_dir = ensure_dir(output_dir / "qualitative")
    sweep_dir = ensure_dir(output_dir / "calibration_sweep")

    all_records, active_records = _manifest_records(cfg)

    all_episodes: list[dict] = []
    per_episode_rows: list[dict[str, Any]] = []
    per_frame_rows: list[dict[str, Any]] = []

    oracle_type = cfg["oracle"]["type"]
    signal_cfg = cfg["signal_validity"]
    process_cfg = cfg["process_validity"]
    output_cfg = cfg["output"]
    signal_frame_agg = signal_cfg.get("frame_aggregation", {})
    process_frame_agg = process_cfg.get("frame_aggregation", signal_frame_agg)

    for episode_idx, record in enumerate(active_records):
        episode = _episode_from_record(
            record,
            oracle_type=oracle_type,
            frame_agg_mode=str(signal_frame_agg.get("mode", "mean")),
            frame_topk_ratio=float(signal_frame_agg.get("topk_ratio", 0.1)),
            frame_quantile=float(signal_frame_agg.get("quantile", 0.95)),
        )
        episode_metrics = compute_episode_signal_metrics(
            episode["risk_map"],
            episode["oracle_error"],
            high_error_qs=signal_cfg["high_error_qs"],
            high_error_scope=signal_cfg["high_error_scope"],
            topk_overlap_enabled=bool(signal_cfg["topk_overlap"]),
            frame_agg_mode=str(signal_frame_agg.get("mode", "mean")),
            frame_topk_ratio=float(signal_frame_agg.get("topk_ratio", 0.1)),
            frame_quantile=float(signal_frame_agg.get("quantile", 0.95)),
        )
        episode["episode_metrics"] = episode_metrics

        if process_cfg["enabled"]:
            episode["process_metrics"] = compute_process_validity_episode(
                risk_map=episode["risk_map"],
                error_map=episode["oracle_error"],
                lag_max=int(process_cfg["lag_max"]),
                risk_topk_ratio=float(process_cfg["risk_topk_ratio"]),
                low_error_quantile=float(process_cfg["low_error_quantile"]),
                stable_delta_quantile=float(process_cfg["stable_delta_quantile"]),
                frame_agg_mode=str(process_frame_agg.get("mode", "mean")),
                frame_topk_ratio=float(process_frame_agg.get("topk_ratio", 0.1)),
                frame_quantile=float(process_frame_agg.get("quantile", 0.95)),
            )
        else:
            episode["process_metrics"] = None

        per_episode_rows.append(_episode_summary_row(episode))
        for frame_idx, (frame_risk, frame_error) in enumerate(zip(episode["frame_risk"], episode["frame_error"])):
            per_frame_rows.append(
                {
                    "episode_id": episode["episode_id"],
                    "split": episode["split"],
                    "frame_idx": frame_idx,
                    "frame_mean_conf": float(np.mean(episode["confidence_map"][frame_idx])),
                    "frame_mean_risk": float(frame_risk),
                    "frame_mean_error": float(frame_error),
                }
            )

        all_episodes.append(episode)

    if cfg["calibration"]["tau_eval"]["mode"] == "quantile" and len(active_records) != len(all_records):
        tau_source_records = []
        for record in all_records:
            wanted_split = cfg["calibration"]["tau_eval"].get("quantile_source_split", "train")
            if record.split != wanted_split:
                continue
            tau_source_records.append(
                _episode_from_record(
                    record,
                    oracle_type=oracle_type,
                    frame_agg_mode=str(signal_frame_agg.get("mode", "mean")),
                    frame_topk_ratio=float(signal_frame_agg.get("topk_ratio", 0.1)),
                    frame_quantile=float(signal_frame_agg.get("quantile", 0.95)),
                )
            )
    else:
        tau_source_records = all_episodes

    tau_operational = resolve_operational_tau(
        episode_records=tau_source_records,
        mode=cfg["calibration"]["tau_eval"]["mode"],
        fixed_value=cfg["calibration"]["tau_eval"].get("fixed_value"),
        quantile=cfg["calibration"]["tau_eval"].get("quantile"),
        quantile_source_split=cfg["calibration"]["tau_eval"].get("quantile_source_split", "train"),
    )

    for idx, episode in enumerate(all_episodes):
        calib = compute_calibration_stats(
            episode["patch_conf"],
            episode["patch_error"],
            tau=tau_operational,
            num_bins=int(cfg["calibration"]["num_bins"]),
            correctness_mode=cfg["calibration"]["correctness_mode"],
            soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
        )
        per_episode_rows[idx]["operational_ece"] = calib["ece"]
        per_episode_rows[idx]["operational_mce"] = calib["mce"]
        per_episode_rows[idx]["operational_brier"] = calib["brier"]

    pooled_conf = np.concatenate([episode["patch_conf"] for episode in all_episodes], axis=0)
    pooled_err = np.concatenate([episode["patch_error"] for episode in all_episodes], axis=0)

    signal_summary = compute_global_signal_summary(
        all_episodes,
        high_error_qs=signal_cfg["high_error_qs"],
        high_error_scope=signal_cfg["high_error_scope"],
        topk_overlap_enabled=bool(signal_cfg["topk_overlap"]),
    )
    operational_calib = compute_calibration_stats(
        pooled_conf,
        pooled_err,
        tau=tau_operational,
        num_bins=int(cfg["calibration"]["num_bins"]),
        correctness_mode=cfg["calibration"]["correctness_mode"],
        soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
    )

    summary: dict[str, Any] = {
        "num_episodes": len(all_episodes),
        "num_frames": int(sum(episode["risk_map"].shape[0] for episode in all_episodes)),
        "num_patches": int(sum(episode["patch_risk"].size for episode in all_episodes)),
        "oracle_type": oracle_type,
        "operational_tau": float(tau_operational),
        "calibration_protocol": "operational",
        "calibration_note": (
            "Main metrics use operational calibration: correctness = 1[oracle_error <= tau_eval] at fixed tau_eval. "
            "Threshold sweep is diagnostic only, not a direct interpretation of the probe as q(x,tau)."
        ),
    }
    summary.update(signal_summary)
    summary["operational_ece"] = operational_calib["ece"]
    summary["operational_mce"] = operational_calib["mce"]
    summary["operational_brier"] = operational_calib["brier"]
    summary["operational_mean_confidence"] = operational_calib["mean_confidence"]
    summary["operational_mean_correctness"] = operational_calib["mean_correctness"]

    process_summary = None
    if cfg["calibration"]["threshold_sweep"]["enabled"]:
        sweep_values = cfg["calibration"]["threshold_sweep"]["values"]
        sweep_results = compute_threshold_sweep(
            pooled_conf,
            pooled_err,
            tau_values=sweep_values,
            num_bins=int(cfg["calibration"]["num_bins"]),
            correctness_mode=cfg["calibration"]["correctness_mode"],
            soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
        )
        sweep_rows = []
        for item in sweep_results:
            sweep_rows.append(
                {
                    "tau": item["tau"],
                    "ece": item["ece"],
                    "mce": item["mce"],
                    "brier": item["brier"],
                    "mean_confidence": item["mean_confidence"],
                    "mean_correctness": item["mean_correctness"],
                    "total_samples": item["total_samples"],
                }
            )
        save_json(sweep_rows, str(sweep_dir / "threshold_sweep_metrics.json"))
        plot_calibration_sweep_dashboard(
            sweep_results=sweep_results,
            path_stem=str(sweep_dir / "calibration_sweep_overview"),
            save_png=bool(output_cfg["save_png"]),
            save_pdf=bool(output_cfg["save_pdf"]),
        )
        summary["threshold_sweep_enabled"] = True
    else:
        summary["threshold_sweep_enabled"] = False
        sweep_results = []

    if process_cfg["enabled"]:
        process_summary = summarize_process_validity(all_episodes, lag_max=int(process_cfg["lag_max"]))
        summary.update(_flatten_summary_dict(process_summary))

    ood_cfg = cfg["ood"]
    ood_summary = None
    if bool(ood_cfg["enabled"]):
        ood_summary = compute_ood_summary(
            all_episodes,
            frame_score_mode=ood_cfg["frame_score_mode"],
            frame_topk_ratio=float(ood_cfg["frame_topk_ratio"]),
            trajectory_score_mode=ood_cfg["trajectory_score_mode"],
        )
        if ood_summary:
            summary["frame_ood_auroc"] = ood_summary["frame_ood_auroc"]
            summary["frame_ood_auprc"] = ood_summary["frame_ood_auprc"]
            summary["trajectory_ood_auroc"] = ood_summary["trajectory_ood_auroc"]
            summary["trajectory_ood_auprc"] = ood_summary["trajectory_ood_auprc"]

        id_conf = np.concatenate([ep["patch_conf"] for ep in all_episodes if not ep["is_ood"]], axis=0) if any(not ep["is_ood"] for ep in all_episodes) else np.zeros(0)
        id_err = np.concatenate([ep["patch_error"] for ep in all_episodes if not ep["is_ood"]], axis=0) if any(not ep["is_ood"] for ep in all_episodes) else np.zeros(0)
        ood_conf = np.concatenate([ep["patch_conf"] for ep in all_episodes if ep["is_ood"]], axis=0) if any(ep["is_ood"] for ep in all_episodes) else np.zeros(0)
        ood_err = np.concatenate([ep["patch_error"] for ep in all_episodes if ep["is_ood"]], axis=0) if any(ep["is_ood"] for ep in all_episodes) else np.zeros(0)
        if id_conf.size > 0:
            id_calib = compute_calibration_stats(
                id_conf,
                id_err,
                tau=tau_operational,
                num_bins=int(cfg["calibration"]["num_bins"]),
                correctness_mode=cfg["calibration"]["correctness_mode"],
                soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
            )
            summary["id_operational_ece"] = id_calib["ece"]
            summary["id_operational_brier"] = id_calib["brier"]
        if ood_conf.size > 0:
            ood_calib = compute_calibration_stats(
                ood_conf,
                ood_err,
                tau=tau_operational,
                num_bins=int(cfg["calibration"]["num_bins"]),
                correctness_mode=cfg["calibration"]["correctness_mode"],
                soft_correctness_mode=cfg["calibration"]["soft_correctness_mode"],
            )
            summary["ood_operational_ece"] = ood_calib["ece"]
            summary["ood_operational_brier"] = ood_calib["brier"]

    summary = _bootstrap_metrics(summary, all_episodes, cfg, tau_operational=tau_operational)

    plot_main_dashboard(
        operational_calib=operational_calib,
        pooled_conf=pooled_conf,
        pooled_err=pooled_err,
        process_summary=process_summary,
        ood_payload=ood_summary,
        summary_payload=summary,
        path_stem=str(plots_dir / "overview"),
        seed=int(cfg["misc"]["seed"]),
        save_png=bool(output_cfg["save_png"]),
        save_pdf=bool(output_cfg["save_pdf"]),
    )

    qual_mode = str(output_cfg.get("qualitative_mode", "single")).lower()
    if qual_mode not in {"none", "single", "full"}:
        raise ValueError(f"Unsupported qualitative_mode: {qual_mode}")
    if qual_mode != "none":
        if qual_mode == "full":
            selected_episodes = [("all", episode, None) for episode in all_episodes]
        else:
            metric_name = str(output_cfg.get("qualitative_metric", "patch_spearman"))
            selected_episodes = _select_qualitative_episodes(all_episodes, metric_name=metric_name)
        for tag, episode, selection_note in selected_episodes:
            if episode["pred_frames"] is not None and episode["gt_frames"] is not None:
                filename = episode["episode_id"] if tag == "all" else f"{tag}__{episode['episode_id']}"
                plot_qualitative_panel(
                    episode_id=episode["episode_id"],
                    gt_frames=episode["gt_frames"],
                    pred_frames=episode["pred_frames"],
                    oracle_error=episode["oracle_error"],
                    risk_map=episode["risk_map"],
                    path_stem=str(qual_dir / filename),
                    selection_note=selection_note,
                    save_png=bool(output_cfg["save_png"]),
                    save_pdf=bool(output_cfg["save_pdf"]),
                )

    if output_cfg.get("save_per_episode_metrics_json", False):
        save_json(per_episode_rows, str(output_dir / "per_episode_metrics.json"))
    if output_cfg.get("save_per_frame_metrics_json", False):
        save_json(per_frame_rows, str(output_dir / "per_frame_metrics.json"))
    save_json(summary, str(output_dir / "summary.json"))
    return summary


def build_argparser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Why Confidence? Evaluation suite")
    parser.add_argument("--config", required=True, help="Path to YAML config")
    parser.add_argument("--manifest", default=None, help="Path to manifest.json or manifest.jsonl")
    parser.add_argument("--split", default=None, help="Only evaluate specified splits (comma-separated)")
    parser.add_argument("--gt_root", default=None, help="GT root dir for auto-completion when manifest lacks GT paths")
    parser.add_argument("--standardized_root", default=None, help="Auto-build manifest from standardized episode dir if manifest not provided")
    parser.add_argument("--oracle_type", default=None, choices=["pixel", "latent"], help="Oracle type")
    parser.add_argument("--tau_mode", default=None, choices=["fixed", "quantile"], help="Operational tau mode")
    parser.add_argument("--tau_fixed", type=float, default=None, help="Fixed tau_eval value")
    parser.add_argument("--tau_quantile", type=float, default=None, help="Quantile tau_eval (train split error quantile)")
    parser.add_argument("--ood_frame_score_mode", default=None, choices=["mean_risk", "topk_mean_risk"], help="OOD frame score aggregation mode")
    parser.add_argument("--ood_frame_topk_ratio", type=float, default=None, help="OOD top-k ratio")
    parser.add_argument("--disable_process_validity", action="store_true", help="Disable process validity")
    parser.add_argument("--output_dir", default=None, help="Output directory")
    parser.add_argument("--qualitative_mode", default=None, choices=["none", "single", "full"], help="Qualitative plot output mode")
    parser.add_argument("--seed", type=int, default=1, help="Random seed")
    parser.add_argument("--enable_bootstrap", action="store_true", help="Enable bootstrap CI")
    parser.add_argument("--disable_bootstrap", action="store_true", help="Disable bootstrap CI")
    parser.add_argument("--num_bootstrap", type=int, default=None, help="Number of bootstrap iterations")
    return parser


def main() -> None:
    parser = build_argparser()
    args = parser.parse_args()
    cfg = _load_config(args.config)
    cfg = _apply_cli_overrides(cfg, args)
    summary = run(cfg)
    print("Why Confidence? evaluation completed")
    print(f"Output directory: {cfg['output']['dir']}")
    print(f"operational_tau: {summary['operational_tau']:.6f}")
    print(f"pooled_patch_spearman: {summary.get('pooled_patch_spearman', float('nan')):.6f}")
    print(f"operational_ece: {summary.get('operational_ece', float('nan')):.6f}")


if __name__ == "__main__":
    main()
