#!/usr/bin/env python3
"""
eval_c3_confidence.py
=====================

A complete "Why Confidence?" evaluation suite for ConfAL-WM's latent confidence probe.

Core semantic assumptions:
1. The current probe may be trained with random threshold + BCE.
2. If tau is not explicitly provided at inference, output cannot be reinterpreted as q(x, tau).
3. Therefore this script uses operational calibration by default:
   Define correctness = 1[oracle_error <= tau_eval] at a fixed tau_eval.
4. Threshold sweep is diagnostic only, not the unique or natural semantic interpretation.

---

Usage examples
---------------

# 1. Simplest main evaluation command

  - Read results_scenes_50/manifest.json
  - Auto-infer GT paths from episode_id
  - Use default settings: pixel oracle + operational calibration
  - Output signal validity, calibration, OOD, process validity and plots

  python3 eval/confidence_eval/eval_c3_confidence.py \
    --config configs/agibotworld/eval_c3_confidence.yaml \
    --manifest logs/c3_dec_latent_temb/results_scenes_50/wcm_dataset/manifest.json \
    --gt_root datasets/AgiBotWorldChallenge-2026/WorldModel/validation/gt_dataset \
    --output_dir logs/c3_dec_latent_temb/why_confidence_results_scenes_50 \
    --tau_mode fixed \
    --tau_fixed 0.25

# 2. Other parameters

  --oracle_type can be "pixel" or "latent"

  Since eval_c3_probe.py auto-outputs manifest.json with train/val splits,
  add --split val if you only want to see validation results.

  For formal scalar intervals in a paper, add:
    --enable_bootstrap \
    --num_bootstrap 500

  Default: --qualitative_mode single (auto-selects best + worst by patch_spearman)
  No qualitative output: --qualitative_mode none
  All episodes: --qualitative_mode full

# 3. Automatically determine operational tau from train split error quantile

  This matches the "main setting + train-set quantile tau" version in the paper.
  Do NOT exclude the train split with --split val, or at least keep train split
  entries in the manifest for tau estimation.

  python3 eval/confidence_eval/eval_c3_confidence.py \
    --config configs/agibotworld/eval_c3_confidence.yaml \
    --manifest logs/c3_probe_v4_dec_latent_temb/results_scenes_50/manifest.json \
    --tau_mode quantile \
    --tau_quantile 0.5 \
    --gt_root datasets/AgiBotWorldChallenge-2026/WorldModel/validation/gt_dataset \
    --output_dir logs/c3_probe_v4_dec_latent_temb/why_confidence_results_scenes_50_tauq50

  To "output val metrics only while tau is still estimated from train split",
  keep the full manifest in the config and only add --split val in the command.
  Current implementation reads the train split additionally to estimate quantile tau.

"""

