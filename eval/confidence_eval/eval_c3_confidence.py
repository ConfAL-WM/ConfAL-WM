def _deep_update(base: dict[str, Any], updates: dict[str, Any]) -> dict[str, Any]:
    for key, value in updates.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            _deep_update(base[key], value)
        else:
            base[key] = value
    return base


def _set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)


def _cleanup_output_artifacts(output_dir: Path) -> None:
    """
    Clean up stale artifacts from old output formats to avoid cluttering the
    directory with PDF/CSV/old subdirectories after re-running in the same dir.
    Only removes artifacts generated by eval_c3_confidence.py; does not touch
    manifest or raw input data.
    """
    stale_patterns = [
        "summary.json",
        "summary.csv",
        "resolved_config.json",
        "resolved_manifest.json",
        "per_episode_metrics.csv",
        "per_frame_metrics.csv",
        "per_episode_metrics.json",
        "per_frame_metrics.json",
        "plots/*.pdf",
        "plots/*.png",
        "calibration_sweep/threshold_sweep_metrics.json",
        "calibration_sweep/*.csv",
        "calibration_sweep/*.pdf",
        "calibration_sweep/*.png",
        "qualitative/*.pdf",
        "qualitative/*.png",
    ]
    for pattern in stale_patterns:
        for path in output_dir.glob(pattern):
            if path.is_file():
                path.unlink(missing_ok=True)
    for path in output_dir.glob("calibration_sweep/tau_*"):
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)


